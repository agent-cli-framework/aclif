// Generate src/providers/index.generated.ts from whatever provider directories
// exist under src/providers/{native,contributed,private}. Adding a provider in
// any tier is creating the directory; nothing else in the repo changes, which
// is what keeps a fork's private providers out of every upstream merge.
//
//   ACI_PROVIDER_TIERS=native,private    build only these tiers
//   ACI_EXCLUDE_PROVIDERS=foo,bar         drop individual providers
//
// Runs on postinstall and prebuild. No-op in a published package (no src/).
import {existsSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs'
import {join} from 'node:path'

const TIERS = ['native', 'contributed', 'private']
const ROOT = 'src/providers'
const OUT = join(ROOT, 'index.generated.ts')

if (!existsSync(ROOT)) process.exit(0)

const wanted = process.env.ACI_PROVIDER_TIERS
  ? process.env.ACI_PROVIDER_TIERS.split(',').map((s) => s.trim()).filter(Boolean)
  : TIERS
for (const t of wanted) if (!TIERS.includes(t)) throw new Error(`ACI_PROVIDER_TIERS: unknown tier '${t}' (known: ${TIERS.join(', ')})`)
const excluded = new Set((process.env.ACI_EXCLUDE_PROVIDERS ?? '').split(',').map((s) => s.trim()).filter(Boolean))

const entries = []
const seen = new Map()
for (const tier of TIERS) {
  if (!wanted.includes(tier)) continue
  const dir = join(ROOT, tier)
  if (!existsSync(dir)) continue
  for (const name of readdirSync(dir).sort()) {
    const providerDir = join(dir, name)
    if (!statSync(providerDir).isDirectory()) continue
    const plugin = join(providerDir, 'plugin.ts')
    if (!existsSync(plugin)) {
      console.warn(`gen-provider-index: ${providerDir} has no plugin.ts; skipped`)
      continue
    }
    if (excluded.has(name)) continue
    const m = readFileSync(plugin, 'utf8').match(/export const (\w+) = defineProvider\(/)
    if (!m) throw new Error(`${plugin}: expected 'export const <x> = defineProvider(' so the registry can import it`)
    if (seen.has(name)) {
      throw new Error(`Provider '${name}' exists in two tiers:\n  ${seen.get(name)}\n  ${plugin}\nRename one, or exclude it with ACI_EXCLUDE_PROVIDERS.`)
    }
    seen.set(name, plugin)
    entries.push({name, tier, symbol: m[1], path: `./${tier}/${name}/plugin.js`})
  }
}
entries.sort((a, b) => TIERS.indexOf(a.tier) - TIERS.indexOf(b.tier) || a.name.localeCompare(b.name))

const lines = [
  '// SPDX-License-Identifier: MIT',
  '// Copyright (c) 2026 Prompt One, Inc.',
  '// GENERATED by scripts/gen-provider-index.mjs from the provider directories present. Do not edit; not committed.',
  "import type {ProviderEntry} from '../core/provider/registry.js'",
  ...entries.map((e) => `import {${e.symbol}} from '${e.path}'`),
  '',
  'export const PROVIDER_ENTRIES: ProviderEntry[] = [',
  ...entries.map((e) => `  {plugin: ${e.symbol}, tier: '${e.tier}'},`),
  ']',
  '',
  ...entries.map((e) => `export {${e.symbol}}`),
  '',
]
const next = lines.join('\n')
const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : undefined
if (current !== next) {
  writeFileSync(OUT, next)
  console.log(`gen-provider-index: ${entries.length} providers (${entries.map((e) => `${e.name}:${e.tier}`).join(', ')})`)
}
